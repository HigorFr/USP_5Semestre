#Mistakes e Slips
    #Mistakes: Erros de planejamento, quando o usuário escolhe erroneamento dentre as opções.
        #Vem de falta de informações, ou falta de analise
        #Há interção e objetivo claro, mas você fez errado

    #Slips: Erros de execução, quando o usuário tem a intenção correta, mas acaba perdendo atenção
        #Não há nem interção

    #Pode ser os dois dependendo do objetivo.


    #Tipos de Slips (lapsos)
        #Lapso de Condicionamento: Quando uma ação mais rara é ofuscada por uma dominante que é mais facimiliar
        #Descritção: Ação correta mas em um objeto errado
