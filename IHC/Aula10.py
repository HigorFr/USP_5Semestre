#Persona
    #Invés do termo universal "usuario", que engloba tudo e todas as pessoas, a persona é uma representação fictícia de um usuário específico, com características, necessidades e comportamentos detalhados. Ela é criada com base em dados reais e tem como objetivo ajudar a equipe de design a entender melhor o público-alvo e a criar soluções mais eficazes e personalizadas, pensando em  alguém específico.
    #Colcam-se fotos, nome, idade e profissão, e outras informações extraídas dos dados, para criar um imaginário no desenvolvimento. Isso para cada um dos perfis.
    #Objetivo tem que estar bem especoficado, pois ele deve ser atendido.
        #Alguns objetivos padrões é fazer ele não se sentir estúpido.

