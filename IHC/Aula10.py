#Cenários
    #Cenários são descrições detalhadas de situações específicas em que um usuário interage com um sistema ou produto. Eles ajudam a entender como os usuários podem usar o sistema em diferentes contextos e a identificar possíveis problemas ou oportunidades de melhoria. É sempre como o sistema é hoje, com foco para analise de problema.

    #Cada utilidade de um sistesma é um caso de uso
        #Ex no jupter web se pode matricular, pedir nota, requerimento, trancamento etc...

    #Não necessario desvrever todos, só os que se julgam mais relevanates.

#Modelo de tarefas
    #Descrição normalmente como em algum algoritimo, exemplo GOMS.
    #GOMS é um modelo de tarefas que descreve as ações que um usuário realiza para alcançar um objetivo específico. Ele é composto por quatro elementos principais: Goals (objetivos), Operators (operações), Methods (métodos) e Selection rules (regras de seleção). O GOMS é usado para analisar a eficiência e a eficácia de interfaces de usuário, identificando possíveis melhorias e otimizando a experiência do usuário.
        #Dá para quebrar em detalhes

    #Tipos de tarefas
    #Concorrentes é uma representação mais simples, que só tem os objetivos e as ações, sem detalhar tanto. Ele é útil para ter uma visão geral do processo e identificar os principais passos envolvidos na realização de uma tarefa, sem se aprofundar em detaemolhes específicos. Ele é mais fácil de criar e entender, mas pode não fornecer informações tão detalhadas quanto o GOMS.


    #Tem muitos outros tipos de tarefas, que não foram aprofundadas.

