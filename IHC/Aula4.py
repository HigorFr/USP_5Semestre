#Interpetação


#Varios modos de interpretar uma mesma interface por diferentes aspectos


#Proximidade
    #Distancia entre objetos afeta a percepção de agrupamento, objetos próximos são percebidos como um grupo, relacionados

#Similaridade
    #Elementos semelhantes são percebidos como parte de um grupo também, como cor, forma, tamanho, etc
    #Exemplo, emails em negrito são do grupo "Não lidos", e os normais são do grupo "Lidos"


#Continuidade
    #Elementos alinhados ou organizados em uma linha ou curva que reaparece parcialmente são entendidos como parte de um mesmo



#Fechaemnto
    #Partes incompletas tendem a ser percebidas como um todo, mesmo que haja lacunas

#Simetria
    #Estruturas compelxas tendem a ser quebradas em menores para haver um entendimento melhor


#Figura e fundo
    #Elementos são percebidos como figura (Foco) ou fundo (Contexto), e isso pode ser influenciado por fatores como cor, contraste, etc
    #Coisas maiores normalmente são o fundo



#Distinto Comum
    #Meio não usado, basicamente uma diferença que torna todos similiares dado um contexto


#Região Comum
    #Delimitação em uma região para destacar


#Ponto Focal
    #Concentração imediata a um elemtno por conta de uma diferença, para chamar atenção

