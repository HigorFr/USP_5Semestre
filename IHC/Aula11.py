#Desing é uma abordagem centrada no usuário para a resolução de problemas e desenvolvimento de soluções inovadoras. Ele envolve a compreensão profunda das necessidades e desejos dos usuários, a geração de ideias criativas, a prototipagem rápida e a iteração constante com base no feedback dos usuários. 
# O Design Thinking é amplamente utilizado em diversas áreas, incluindo design de produtos, serviços, experiências e processos, promovendo a colaboração interdisciplinar e a empatia com os usuários finais.
