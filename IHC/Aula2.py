#Affrodance
    #Affrodance é a propriedade de um objeto que indica como ele pode ser usado, ou seja, quais ações ele permite. Por exemplo, um botão tem a affrodance de ser clicado, uma alavanca tem a affrodance de ser puxada, etc... A affrodance é importante para a usabilidade da interface, pois ajuda o usuário a entender como interagir com ela.
