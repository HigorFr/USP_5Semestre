    #Sistema com servidor, com vários clientes. Dependente totalmente de um ponto.
    #Decentralizado: Feito por necessidade, sistemas com muito centros (vários servidores conectados) ou P2Ps
    #Distribuído: Suficientemente espalhados, relacionado a desempenho, confiabilidade.
        #Confiabilidade bem relacionado com redundância. Criar novos servidores, e manter consistência entre dados.


